test('暫存器初值、負數與記憶體末頁', async ({ page }) => {
  await configure(page, { source: 'lw $t1, 1020($zero)\naddu $t2, $t0, $t1\nsw $t2, 1020($zero)', registers: '$t0 = -1', memory: '0x03FC = 7' })
  await run(page)
  await cycle(page, 'last')
  await expect(register(page, 't0')).toHaveText('0xFFFFFFFF')
  await expect(register(page, 't0')).toHaveAttribute('title', '-1')
  await expect(register(page, 't2')).toHaveText('0x00000006')
  await expect(page.getByRole('button', { name: '上一頁記憶體' })).toBeDisabled()
  for (let n = 0; n < 15; n++) await page.getByRole('button', { name: '下一頁記憶體' }).click()
  await expect(page.locator('.memory-heading code')).toHaveText('16/16')
  await expect(page.getByRole('button', { name: '下一頁記憶體' })).toBeDisabled()
  await expect(memory(page, '0x03FC')).toHaveText('0x00000006')
  await expect(memory(page, '0x03FC')).toHaveAttribute('title', '6 · bytes (LE): 06 00 00 00')
  await page.getByRole('button', { name: '上一頁記憶體' }).click()
  await expect(page.locator('.memory-heading code')).toHaveText('15/16')
})

