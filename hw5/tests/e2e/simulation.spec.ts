test('播放速度、暫停與自動停止', async ({ page }) => {
  await configure(page, { source: 'addi $t0, $zero, 7' })
  await run(page)
  await page.clock.install()
  await page.getByRole('combobox', { name: '播放速度' }).selectOption('0.5')
  await page.getByRole('button', { name: '播放模擬' }).click()
  await page.clock.runFor(1600)
  await expect(metric(page, 'CLOCK CYCLE')).toHaveText('002')
  await page.getByRole('button', { name: '暫停播放' }).click()
  await page.clock.runFor(3200)
  await expect(metric(page, 'CLOCK CYCLE')).toHaveText('002')
  await page.getByRole('combobox', { name: '播放速度' }).selectOption('4')
  await page.getByRole('button', { name: '播放模擬' }).click()
  await page.clock.runFor(200)
  await expect(metric(page, 'CLOCK CYCLE')).toHaveText('003')
  await page.clock.runFor(400)
  await expect(metric(page, 'CLOCK CYCLE')).toHaveText('005')
  await expect(page.getByRole('button', { name: '播放模擬' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '暫停播放' })).toHaveCount(0)
})

