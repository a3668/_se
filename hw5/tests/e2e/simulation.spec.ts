const examples = [
  { index: '0', title: 'Forwarding & load-use', registers: { t0: '0x00000007', t1: '0x0000000E', t2: '0x00000011', t3: '0x00000011' }, memory: { '0x0004': '0x00000011', '0x0008': '0x00000011' }, retired: '6' },
  { index: '1', title: 'Branch & flush', registers: { s0: '0x00000000', s1: '0x0000002A' }, memory: { '0x0000': '0x00000000', '0x0004': '0x0000002A' }, retired: '5' },
  { index: '2', title: 'Loop & dependencies', registers: { t0: '0x00000000', s0: '0x0000000F' }, memory: { '0x0000': '0x0000000F' }, retired: '18' },
  { index: '3', title: 'Jump & link', registers: { a0: '0x00000006', v0: '0x0000000C', ra: '0x00000008' }, memory: { '0x0000': '0x0000000C' }, retired: '7' },
]
for (const example of examples) {
  test(`教學範例：${example.title}`, async ({ page }) => {
    await page.getByLabel('載入教學範例').selectOption(example.index)
    await expect(page.locator('#program-title')).toHaveValue(example.title)
    await run(page)
    await cycle(page, 'last')
    for (const [name, value] of Object.entries(example.registers)) await expect(register(page, name)).toHaveText(value)
    for (const [address, value] of Object.entries(example.memory)) await expect(memory(page, address)).toHaveText(value)
    await expect(metric(page, 'RETIRED')).toHaveText(example.retired)
    if (example.index === '0') await expect(metric(page, 'STALL / FLUSH')).toHaveText('1 / 0')
    if (example.index === '1') await expect(metric(page, 'STALL / FLUSH')).toHaveText('0 / 2')
  })
}

