import { test, expect, configure, run, save, cycle, register, history, confirm } from './helpers.js'

test('程式新增、更新與重新整理後載入', async ({ page, request }) => {
  await configure(page, { title: '持久化草稿', source: 'addi $t0, $zero, 7', registers: '$a0 = -1', memory: '0 = 9', maxCycles: 20 })
  const saved = await save(page)
  await expect(page.getByLabel(/程式名稱/)).toHaveValue('持久化草稿')
  await page.getByRole('textbox', { name: 'MIPS 組合語言' }).fill('addi $t0, $zero, 8')
  expect((await save(page)).id).toBe(saved.id)
  expect(await (await request.get('/api/v1/programs')).json()).toHaveLength(1)
  await page.reload()
  await history(page)
  await expect(page.locator('.saved-card')).toHaveCount(1)
  await page.getByRole('button', { name: '載入程式' }).click()
  await expect(page.getByRole('textbox', { name: 'MIPS 組合語言' })).toHaveValue('addi $t0, $zero, 8')
  await expect(page.locator('#init-registers')).toHaveValue('$a0 = 0xFFFFFFFF')
  await expect(page.locator('#init-memory')).toHaveValue('0x0000 = 0x00000009')
  await expect(page.getByLabel('Cycle 上限')).toHaveValue('20')
  await run(page)
  await cycle(page, 'last')
  await expect(register(page, 't0')).toHaveText('0x00000008')
  await expect(register(page, 'a0')).toHaveText('0xFFFFFFFF')
})

